def write_csv(path: Path, fieldnames: list[str], rows: list[dict[str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, quoting=csv.QUOTE_ALL, lineterminator="\r\n")
        writer.writeheader()
        writer.writerows(rows)


def convert_photo(community_id: str, folder: str, filename: str) -> None:
    source = CONFIRMED / folder / filename
    if not source.exists():
        raise FileNotFoundError(source)
    IMAGE_OUTPUT.mkdir(parents=True, exist_ok=True)
    with Image.open(source) as image:
        image = ImageOps.exif_transpose(image).convert("RGB")
        image = ImageOps.fit(image, (1280, 720), method=Image.Resampling.LANCZOS, centering=(0.5, 0.5))
        image.save(IMAGE_OUTPUT / f"{community_id}.webp", "WEBP", quality=84, method=6)


def main() -> None:
    with SOURCE_CSV.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        fieldnames = list(reader.fieldnames or [])
        rows = list(reader)

    if len(rows) != 30 or len(fieldnames) != 14:
        raise ValueError("Expected 30 community rows and 14 columns")
    if len({row["社區ID"] for row in rows}) != 30:
        raise ValueError("Community IDs must be unique")

    changed = []
    for row in rows:
        community_id = row["社區ID"]
        update = UPDATES.get(community_id)
        if not update:
            continue
        row["社區簡介"] = update["intro"]
        row["計畫成果重點"] = update["highlights"]
        photo = update.get("photo")
        if photo:
            convert_photo(community_id, *photo)
            row["社區照片網址"] = f"./assets/community/{community_id}.webp"
            row["照片替代文字"] = update["alt"]
        changed.append(community_id)

    if set(changed) != set(UPDATES):
        raise ValueError("Not every confirmed community was updated")
    for path in CSV_OUTPUTS:
        write_csv(path, fieldnames, rows)
    print(f"Updated {len(changed)} confirmed communities and {sum('photo' in value for value in UPDATES.values())} photos")


if __name__ == "__main__":
    main()
